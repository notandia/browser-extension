'use strict';

// Convert two pinned Wikimedia wikitext lists to a local declarative snapshot.
// Usage: node scripts/import-community-publishing.js publishers.txt journals.txt
const fs = require('node:fs');
const path = require('node:path');

const SOURCES = [
  { title: 'Cite Unseen: predatory publishers', scope: 'publisher', revision: 30328516, date: '2026-03-30', url: 'https://meta.wikimedia.org/w/index.php?title=Cite_Unseen/sources/predatory/publishers&oldid=30328516' },
  { title: 'Cite Unseen: predatory standalone journals', scope: 'journal', revision: 30328518, date: '2026-03-30', url: 'https://meta.wikimedia.org/w/index.php?title=Cite_Unseen/sources/predatory/standaloneJournals&oldid=30328518' }
];

function extractEntries(source) {
  const templates = source.match(/\{\{CULink\b/gi) || [];
  const entries = Array.from(source.matchAll(/\{\{CULink\s*\|\s*url\s*=\s*([^|}]+)/gi), match => match[1].trim());
  if (!entries.length || entries.length !== templates.length) throw new Error('Unparsed source entries');
  for (const entry of entries) {
    const url = new URL(/^[a-z]+:\/\//i.test(entry) ? entry : `https://${entry}`);
    if (!/^https?:$/.test(url.protocol) || url.username || url.password || !url.hostname.includes('.')) throw new Error(`Unsupported source URL: ${entry}`);
  }
  return entries;
}

function generate(files) {
  const sources = SOURCES.map((source, index) => ({ ...source, entries: extractEntries(fs.readFileSync(files[index], 'utf8')) }));
  const data = { edition: '2026-03-30', reviewed: '2026-10-04', license: 'CC-BY-SA-4.0', attribution: 'Wikimedia contributors; adapted from the linked pinned revisions. URL entries are preserved; matching rules are compiled locally.', sources };
  const existing = require('../shared/community_publishing_data.js');
  if (existing.citewatch) data.citewatch = existing.citewatch;
  const output = `'use strict';\n\n// Generated by scripts/import-community-publishing.js.\n// Dataset: Wikimedia contributors, CC BY-SA 4.0.\n// Attribution, pinned revisions and original URL entries are embedded below.\n;(function exposeCommunityPublishingData(root) {\n  const data = ${JSON.stringify(data, null, 2)};\n  if (typeof module === 'object' && module.exports) module.exports = data;\n  root.NotandiaCommunityPublishingData = data;\n})(typeof globalThis === 'object' ? globalThis : this);\n`;
  fs.writeFileSync(path.join(__dirname, '../shared/community_publishing_data.js'), output);
  return sources.map(source => ({ title: source.title, entries: source.entries.length, revision: source.revision }));
}

if (require.main === module) {
  if (process.argv.length !== 4) throw new Error('Supply the publisher and standalone-journal wikitext files');
  console.log(JSON.stringify(generate(process.argv.slice(2))));
}
module.exports = { extractEntries };
